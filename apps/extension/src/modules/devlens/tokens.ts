/** Builds exportable design tokens / CSS variables from extracted DevLens data. Pure. */
import type { ColorSwatch, TypographyStyle } from '@ntm/shared';

export interface DesignTokens {
  $schema: string;
  meta: { source: string; generatedAt: string; generator: string };
  color: Record<string, { value: string; usages: string[]; occurrences: number }>;
  typography: Record<
    string,
    {
      fontFamily: string;
      fontSize: string;
      fontWeight: string;
      lineHeight: string;
      letterSpacing: string;
      occurrences: number;
    }
  >;
  fontFamily: Record<string, string>;
}

function slug(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/["']/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 40) || 'token'
  );
}

export function primaryFamily(fontFamily: string): string {
  return (fontFamily.split(',')[0] ?? fontFamily).trim().replace(/^["']|["']$/g, '');
}

export function buildDesignTokens(
  colors: ColorSwatch[],
  typography: TypographyStyle[],
  sourceUrl: string,
  now = new Date(),
): DesignTokens {
  const color: DesignTokens['color'] = {};
  colors.forEach((c, i) => {
    const role = c.usages.length === 1 ? c.usages[0] : 'mixed';
    color[`${role}-${i + 1}`] = { value: c.hex, usages: [...c.usages], occurrences: c.count };
  });

  const typo: DesignTokens['typography'] = {};
  const families: Record<string, string> = {};
  typography.forEach((t, i) => {
    typo[`${slug(t.sampleTag)}-${i + 1}`] = {
      fontFamily: t.fontFamily,
      fontSize: t.fontSize,
      fontWeight: t.fontWeight,
      lineHeight: t.lineHeight,
      letterSpacing: t.letterSpacing,
      occurrences: t.count,
    };
    const fam = primaryFamily(t.fontFamily);
    const key = slug(fam);
    if (!families[key]) families[key] = t.fontFamily;
  });

  return {
    $schema: 'https://ntm-sentinel.local/schemas/design-tokens.v1.json',
    meta: { source: sourceUrl, generatedAt: now.toISOString(), generator: 'NTM Sentinel DevLens' },
    color,
    typography: typo,
    fontFamily: families,
  };
}

/** CSS custom-property declarations wrapped in :root. Values come from computed styles. */
export function buildCssVariables(tokens: DesignTokens): string {
  const lines: string[] = [`/* Generated by NTM Sentinel DevLens from ${sanitizeComment(tokens.meta.source)} */`, ':root {'];
  for (const [k, v] of Object.entries(tokens.color)) lines.push(`  --color-${slug(k)}: ${v.value};`);
  for (const [k, v] of Object.entries(tokens.fontFamily)) lines.push(`  --font-${slug(k)}: ${v};`);
  for (const [k, v] of Object.entries(tokens.typography)) {
    const n = slug(k);
    lines.push(`  --text-${n}-size: ${v.fontSize};`);
    lines.push(`  --text-${n}-weight: ${v.fontWeight};`);
    lines.push(`  --text-${n}-line-height: ${v.lineHeight};`);
    if (v.letterSpacing && v.letterSpacing !== 'normal') lines.push(`  --text-${n}-letter-spacing: ${v.letterSpacing};`);
  }
  lines.push('}');
  return lines.join('\n') + '\n';
}

function sanitizeComment(s: string): string {
  return s.replace(/\*\//g, '* /').slice(0, 300);
}

/** "prop: value;" lines for copying an element's styles. */
export function toCssDeclarations(styles: Record<string, string>): string {
  return Object.entries(styles)
    .filter(([, v]) => v !== '' && v !== undefined)
    .map(([k, v]) => `${k}: ${v};`)
    .join('\n');
}

export function toCssRule(selector: string, styles: Record<string, string>): string {
  const body = toCssDeclarations(styles)
    .split('\n')
    .filter(Boolean)
    .map((l) => `  ${l}`)
    .join('\n');
  return `${selector} {\n${body}\n}\n`;
}
